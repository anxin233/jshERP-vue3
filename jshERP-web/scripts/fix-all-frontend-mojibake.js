// 去重（保留最长匹配优先已 sort）
const seen = new Set()
const unique = []
for (const pair of REPLACEMENTS) {
  if (!seen.has(pair[0])) {
    seen.add(pair[0])
    unique.push(pair)
  }
}

function walk(dir, files = []) {
  if (!fs.existsSync(dir)) return files
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === 'dist') continue
    const f = path.join(dir, e.name)
    if (e.isDirectory()) walk(f, files)
    else if (/\.(vue|js|html|less)$/.test(e.name)) files.push(f)
  }
  return files
}

let fileCount = 0
let replaceCount = 0
const files = walk(path.join(WEB, 'src'))
if (fs.existsSync(path.join(WEB, 'index.html'))) files.push(path.join(WEB, 'index.html'))

for (const f of files) {
  let c = fs.readFileSync(f, 'utf8')
  const orig = c
  for (const [from, to] of unique) {
    if (c.includes(from)) {
      const n = c.split(from).length - 1
      c = c.split(from).join(to)
      replaceCount += n
    }
  }
  if (c !== orig) {
    fs.writeFileSync(f, c, 'utf8')
    fileCount++
    console.log(path.relative(WEB, f))
  }
}

console.log(`\nupdated ${fileCount} files, ${replaceCount} replacements`)
